import assert from 'node:assert/strict';
import {minor,equalShares,percentShare,validateExpense,costSummary,renderCosts,paymentDue,costEntries} from './costs.js';
import {sharedData} from './privacy-ui.js';
const cost={title:'Hotel',amount:100,currency:'GBP',paid_by:'Me',vendor_paid:30,splits:[{person:'Hannah',share:20,repaid:5}]};
assert.equal(equalShares(100,'GBP',2),33.33);
assert.equal(equalShares(100,'JPY',2),33);
assert.equal(percentShare(386.04,'GBP',20),77.21);
assert.equal(minor(0.29,'GBP'),29);
assert.throws(()=>minor(1.5,'JPY'));
assert.throws(()=>minor(Infinity,'GBP'));
assert.throws(()=>validateExpense({...cost,vendor_paid:101}));
assert.throws(()=>validateExpense({...cost,splits:[{person:'Me',share:20,repaid:0}]}));
assert.throws(()=>validateExpense({...cost,splits:[{person:'Hannah',share:20,repaid:21}]}));
assert.throws(()=>validateExpense({...cost,splits:[{person:'Hannah',share:80,repaid:0},{person:'Alex',share:30,repaid:0}]}));
assert.throws(()=>validateExpense({...cost,splits:[{person:'Hannah',share:20,repaid:0},{person:' hannah ',share:20,repaid:0}]}));
assert.equal(validateExpense({...cost,currency:' gbp '}).currency,'GBP');
const summary=costSummary([cost,{...cost,currency:'JPY',vendor_paid:null,splits:[]}]);
assert.deepEqual(summary.currencies[0],{currency:'GBP',total:100,paid:30,vendorDue:70,unknown:0,repayDue:15});
assert.equal(summary.currencies[1].unknown,1);
assert.equal(summary.people[0].due,15);
const safe=sharedData({bookings:[{id:'secret',trip_id:'t',visibility:'private'}],trip_expenses:[{...cost,id:'e',trip_id:'t',booking_id:'secret',visibility:'shared'},{...cost,id:'p',visibility:'private'}]});
assert.equal(safe.trip_expenses.length,0);
assert(!renderCosts({trip_expenses:[cost]},{canEdit:false}).includes('settle-expense'));
assert(renderCosts({trip_expenses:[cost]},{canEdit:true}).includes('Hannah repaid'));
assert(!renderCosts({trip_expenses:[{...cost,title:'<img onerror=x>'}]}).includes('<img'));
console.log('PASS: money precision, split rounding, partial payments, validation, separate currencies, parent privacy, read-only actions, escaping');

assert.deepEqual(paymentDue({...cost,due_date:'2026-11-08'},'2026-11-09'),{label:'Overdue · 8 Nov',kind:'overdue'});
assert.deepEqual(paymentDue({...cost,due_date:'2026-11-09'},'2026-11-09'),{label:'Due today',kind:'soon'});
assert.deepEqual(paymentDue({...cost,due_date:'2026-11-12'},'2026-11-09'),{label:'Due 12 Nov',kind:'soon'});
assert.equal(paymentDue({...cost,due_date:'2026-12-24'},'2026-11-09').kind,'upcoming');
assert.equal(paymentDue({...cost,due_date:'2026-11-08',vendor_paid:100},'2026-11-09').kind,'paid');
assert.equal(paymentDue(cost,'2026-11-09').label,'');
assert(paymentDue({...cost,due_date:'2027-01-10'},'2026-11-09').label.includes('2027'));
const dueHTML=renderCosts({trip_expenses:[{...cost,id:'test',due_date:'2026-11-08'}]},{today:'2026-11-09',expandedId:'test'});
assert(dueHTML.includes('Overdue · 8 Nov'));
assert(dueHTML.includes('data-cost-id="test" open'));
assert(!renderCosts({trip_expenses:[{...cost,due_date:'2026-11-08',vendor_paid:100}]},{today:'2026-11-09'}).includes('Overdue'));
console.log('PASS: due today, overdue, upcoming, paid-date suppression, year boundaries and expanded state');

const bookings=[{id:'booking1',trip_id:'t',title:'Known hotel',amount:500,currency:'GBP',visibility:'shared'}, {id:'cancelled',amount:50,status:'cancelled'}, {id:'unknown',amount:null}];
const initial=costEntries({bookings,trip_expenses:[]});
assert.equal(initial.length,1);assert.equal(initial[0].vendor_paid,null);assert.equal(initial[0].amount,500);
const automaticHTML=renderCosts({bookings,trip_expenses:[]});
assert(automaticHTML.includes('Known hotel'));assert(!automaticHTML.includes('No matching costs'));assert(!automaticHTML.includes('Track an existing booking'));assert(automaticHTML.includes('Not recorded'));
const saved={...cost,id:'cost1',booking_id:'booking1'};
assert.equal(costEntries({bookings,trip_expenses:[saved]}).length,1,'Saved booking costs must replace the automatic row');
assert.equal(costEntries({bookings,trip_expenses:[saved]})[0].vendor_paid,30,'Saved payment records win over booking data');
assert.equal(costEntries(sharedData({bookings:[{...bookings[0],visibility:'private'}],trip_expenses:[]})).length,0,'Private bookings cannot create shared preview cost rows');
assert(!renderCosts({bookings,trip_expenses:[]},{canEdit:false}).includes('settle-expense'));
console.log('PASS: existing bookings appear automatically, payment status remains unknown, cancelled/unpriced bookings excluded, saved costs deduplicate, shared preview and read-only access preserved');
